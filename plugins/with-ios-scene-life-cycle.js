// @ts-check
/**
 * iOS: adopt the UIScene life cycle, which the iOS 27 SDK (Xcode 27)
 * requires. Without it the app is killed at launch with "UIScene life cycle
 * is required for apps built with this SDK".
 *
 * Expo SDK 57's native template still starts React Native from the app
 * delegate with a scene-less window; SDK 58 moved that into a scene
 * delegate (`ExpoAppSceneDelegate`). This plugin does the same for SDK 57,
 * so the generated ios/ folder (never committed, see .gitignore) comes out
 * right on every `npx expo prebuild`:
 *
 * 1. Info.plist gets a single-window `UIApplicationSceneManifest` naming
 *    `SceneDelegate`.
 * 2. `SceneDelegate.swift` is written next to AppDelegate.swift and added
 *    to the app target. It creates the window from the scene, starts React
 *    Native in it (passing a cold-start link the way `Linking.getInitialURL`
 *    reads it), and hands links, universal links and the
 *    active/background changes on to the app delegate, which UIKit no longer
 *    calls for those under scenes. Every Expo module that listens through
 *    the app delegate (the development client's links, notifications,
 *    updates) keeps working that way.
 * 3. AppDelegate.swift no longer creates the window or starts React Native.
 *
 * Remove this plugin when the app moves to Expo SDK 58 or later: its own
 * template ships the scene delegate.
 */
const fs = require("node:fs");
const path = require("node:path");

const {
  IOSConfig,
  withAppDelegate,
  withDangerousMod,
  withInfoPlist,
  withXcodeProject,
} = require("expo/config-plugins");

const SCENE_DELEGATE_FILE = "SceneDelegate.swift";
const APP_DELEGATE_MARKER = "with-ios-scene-life-cycle";

/** The SDK 57 template's window creation and React Native start, in
 * `application(_:didFinishLaunchingWithOptions:)`. */
const APP_DELEGATE_START_BLOCK =
  /#if os\(iOS\) \|\| os\(tvOS\)\n\s*window = UIWindow\(frame: UIScreen\.main\.bounds\)\n\s*factory\.startReactNative\(\n\s*withModuleName: "main",\n\s*in: window,\n\s*launchOptions: launchOptions\)\n#endif\n/;

const SCENE_MANIFEST = {
  UIApplicationSupportsMultipleScenes: false,
  UISceneConfigurations: {
    UIWindowSceneSessionRoleApplication: [
      {
        UISceneConfigurationName: "Default Configuration",
        UISceneDelegateClassName: "$(PRODUCT_MODULE_NAME).SceneDelegate",
      },
    ],
  },
};

const SCENE_DELEGATE_SWIFT = `// Generated by plugins/with-ios-scene-life-cycle.js on \`npx expo prebuild\`.
// Do not edit: change the plugin instead.
//
// The iOS 27 SDK requires the UIScene life cycle. This scene delegate creates
// the window and starts React Native in it (AppDelegate only builds the
// factory), and hands links and life-cycle changes on to the app delegate,
// where Expo's modules listen for them.
import React
import UIKit

@objc(SceneDelegate)
class SceneDelegate: UIResponder, UIWindowSceneDelegate {
  var window: UIWindow?

  private var appDelegate: AppDelegate? {
    return UIApplication.shared.delegate as? AppDelegate
  }

  func scene(
    _ scene: UIScene,
    willConnectTo session: UISceneSession,
    options connectionOptions: UIScene.ConnectionOptions
  ) {
    guard let windowScene = scene as? UIWindowScene,
      let appDelegate = appDelegate,
      let factory = appDelegate.reactNativeFactory
    else {
      return
    }

    let window = UIWindow(windowScene: windowScene)
    self.window = window
    // Code that reads UIApplication.shared.delegate?.window keeps working.
    appDelegate.window = window

    // Linking.getInitialURL() reads a cold-start link from the launch
    // options, which UIKit leaves empty under scenes: rebuild them.
    let browsingWebActivity = connectionOptions.userActivities.first {
      $0.activityType == NSUserActivityTypeBrowsingWeb
    }
    factory.startReactNative(
      withModuleName: "main",
      in: window,
      launchOptions: Self.launchOptions(
        url: connectionOptions.urlContexts.first?.url,
        userActivity: browsingWebActivity
      )
    )

    for context in connectionOptions.urlContexts {
      _ = appDelegate.application(
        UIApplication.shared, open: context.url, options: Self.openURLOptions(from: context.options))
    }
    for activity in connectionOptions.userActivities {
      _ = appDelegate.application(UIApplication.shared, continue: activity, restorationHandler: { _ in })
    }
  }

  func sceneDidDisconnect(_ scene: UIScene) {
    window = nil
  }

  func sceneDidBecomeActive(_ scene: UIScene) {
    appDelegate?.applicationDidBecomeActive(UIApplication.shared)
  }

  func sceneWillResignActive(_ scene: UIScene) {
    appDelegate?.applicationWillResignActive(UIApplication.shared)
  }

  func sceneWillEnterForeground(_ scene: UIScene) {
    appDelegate?.applicationWillEnterForeground(UIApplication.shared)
  }

  func sceneDidEnterBackground(_ scene: UIScene) {
    appDelegate?.applicationDidEnterBackground(UIApplication.shared)
  }

  func scene(_ scene: UIScene, openURLContexts URLContexts: Set<UIOpenURLContext>) {
    guard let appDelegate = appDelegate else {
      return
    }
    for context in URLContexts {
      _ = appDelegate.application(
        UIApplication.shared, open: context.url, options: Self.openURLOptions(from: context.options))
    }
  }

  func scene(_ scene: UIScene, continue userActivity: NSUserActivity) {
    _ = appDelegate?.application(UIApplication.shared, continue: userActivity, restorationHandler: { _ in })
  }

  private static func launchOptions(
    url: URL?,
    userActivity: NSUserActivity?
  ) -> [UIApplication.LaunchOptionsKey: Any]? {
    var launchOptions: [UIApplication.LaunchOptionsKey: Any] = [:]
    if let url = url {
      launchOptions[UIApplication.LaunchOptionsKey(rawValue: "UIApplicationLaunchOptionsURLKey")] = url
    }
    if let userActivity = userActivity {
      launchOptions[UIApplication.LaunchOptionsKey(rawValue: "UIApplicationLaunchOptionsUserActivityDictionaryKey")] = [
        "UIApplicationLaunchOptionsUserActivityTypeKey": userActivity.activityType,
        "UIApplicationLaunchOptionsUserActivityKey": userActivity,
      ]
    }
    return launchOptions.isEmpty ? nil : launchOptions
  }

  private static func openURLOptions(
    from sceneOptions: UIScene.OpenURLOptions
  ) -> [UIApplication.OpenURLOptionsKey: Any] {
    var options: [UIApplication.OpenURLOptionsKey: Any] = [:]
    if let sourceApplication = sceneOptions.sourceApplication {
      options[.sourceApplication] = sourceApplication
    }
    if let annotation = sceneOptions.annotation {
      options[.annotation] = annotation
    }
    options[.openInPlace] = sceneOptions.openInPlace
    return options
  }
}
`;

/**
 * Takes the window creation and React Native start out of the generated
 * AppDelegate.swift. Idempotent; throws when the template no longer has
 * the expected block, so a template change fails the prebuild loudly
 * instead of starting React Native twice.
 * @param {string} contents
 * @returns {string}
 */
function removeAppDelegateWindowStart(contents) {
  if (contents.includes(APP_DELEGATE_MARKER)) {
    return contents;
  }
  if (!APP_DELEGATE_START_BLOCK.test(contents)) {
    throw new Error(
      "with-ios-scene-life-cycle: AppDelegate.swift no longer contains the Expo SDK 57 window " +
        "start block. If the app moved to Expo SDK 58 or later, remove this plugin.",
    );
  }
  return contents.replace(
    APP_DELEGATE_START_BLOCK,
    `    // ${APP_DELEGATE_MARKER}: SceneDelegate.swift creates the window and starts\n` +
      "    // React Native (UIScene life cycle, required by the iOS 27 SDK).\n",
  );
}

/**
 * @param {Record<string, unknown>} infoPlist
 * @returns {Record<string, unknown>}
 */
function addSceneManifest(infoPlist) {
  return { ...infoPlist, UIApplicationSceneManifest: SCENE_MANIFEST };
}

/** @type {import("expo/config-plugins").ConfigPlugin} */
const withIosSceneLifeCycle = (config) => {
  config = withInfoPlist(config, (mod) => {
    mod.modResults = /** @type {typeof mod.modResults} */ (
      addSceneManifest(mod.modResults)
    );
    return mod;
  });

  config = withAppDelegate(config, (mod) => {
    if (mod.modResults.language !== "swift") {
      throw new Error("with-ios-scene-life-cycle: expected a Swift AppDelegate.");
    }
    mod.modResults.contents = removeAppDelegateWindowStart(mod.modResults.contents);
    return mod;
  });

  config = withDangerousMod(config, [
    "ios",
    async (mod) => {
      const projectName = IOSConfig.XcodeUtils.getProjectName(mod.modRequest.projectRoot);
      const target = path.join(
        mod.modRequest.platformProjectRoot,
        projectName,
        SCENE_DELEGATE_FILE,
      );
      await fs.promises.writeFile(target, SCENE_DELEGATE_SWIFT);
      return mod;
    },
  ]);

  config = withXcodeProject(config, (mod) => {
    const projectName = IOSConfig.XcodeUtils.getProjectName(mod.modRequest.projectRoot);
    const filepath = `${projectName}/${SCENE_DELEGATE_FILE}`;
    if (!mod.modResults.hasFile(filepath)) {
      IOSConfig.XcodeUtils.addBuildSourceFileToGroup({
        filepath,
        groupName: projectName,
        project: mod.modResults,
      });
    }
    return mod;
  });

  return config;
};

module.exports = withIosSceneLifeCycle;
module.exports.removeAppDelegateWindowStart = removeAppDelegateWindowStart;
module.exports.addSceneManifest = addSceneManifest;
module.exports.SCENE_DELEGATE_SWIFT = SCENE_DELEGATE_SWIFT;
