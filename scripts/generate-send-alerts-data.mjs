// Writes the two data files the send-alerts edge function vendors from the
// app, because Deno cannot import the app's modules or its locale JSON:
//   supabase/functions/send-alerts/gazetteer-data.ts  (src/features/geo/gazetteer.ts)
//   supabase/functions/send-alerts/strings.ts         (src/i18n/locales/*.json)
// Run after changing a gazetteer town or one of the strings listed below:
//   node scripts/generate-send-alerts-data.mjs        (Node 23+, strips TS types)
// supabase/functions/send-alerts/__tests__/vendored-sync.test.ts fails until
// both files match the app again.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const out = join(root, "supabase/functions/send-alerts");
const { GAZETTEER_CITIES } = await import(join(root, "src/features/geo/gazetteer.ts"));

const LOCALES = ["en", "ckb", "kmr", "ar"];
/** [key in strings.ts, dotted path in the locale JSON] */
export const STRING_KEYS = [
  ["magnitude", "events.magnitudeDisplay"],
  ["alertTitle", "notificationSettings.rehearsal.exampleTitle"],
  ["placeTemplate", "geo.placeLine.template"],
  ["placeWithRegion", "geo.placeLine.withRegion"],
  ["placeCoordinates", "geo.placeLine.coordinates"],
  ["km", "units.km"],
  ["dir_n", "geo.directions.n"],
  ["dir_ne", "geo.directions.ne"],
  ["dir_e", "geo.directions.e"],
  ["dir_se", "geo.directions.se"],
  ["dir_s", "geo.directions.s"],
  ["dir_sw", "geo.directions.sw"],
  ["dir_w", "geo.directions.w"],
  ["dir_nw", "geo.directions.nw"],
  ["region_kurdistanIraq", "geo.regions.kurdistanIraq"],
  ["region_iraq", "geo.regions.iraq"],
  ["region_iran", "geo.regions.iran"],
  ["region_turkey", "geo.regions.turkey"],
  ["region_syria", "geo.regions.syria"],
  ["updateTitle", "alerts.push.updateTitle"],
  ["updateBody", "alerts.push.updateBody"],
  ["summaryTitle", "alerts.push.summaryTitle"],
  ["summaryBody", "alerts.push.summaryBody"],
  ["testTitle", "alerts.push.testTitle"],
  ["testBody", "alerts.push.testBody"],
];

function pick(obj, dotted) {
  return dotted.split(".").reduce((value, part) => (value == null ? value : value[part]), obj);
}

const strings = {};
for (const locale of LOCALES) {
  const json = JSON.parse(readFileSync(join(root, `src/i18n/locales/${locale}.json`), "utf8"));
  strings[locale] = {};
  for (const [key, path] of STRING_KEYS) {
    const value = pick(json, path);
    if (typeof value !== "string") {
      throw new Error(`${locale}: missing ${path}`);
    }
    strings[locale][key] = value;
  }
}

const header = (source) =>
  `// GENERATED by scripts/generate-send-alerts-data.mjs from ${source}.\n` +
  "// Do not edit by hand: change the source, run the script, commit both.\n";

writeFileSync(
  join(out, "strings.ts"),
  header("src/i18n/locales/*.json") +
    "\nexport const STRINGS = " +
    JSON.stringify(strings, null, 2) +
    " as const;\n\nexport type AlertLocale = keyof typeof STRINGS;\n",
);

const cities = GAZETTEER_CITIES.map((city) => ({
  id: city.id,
  names: city.names,
  lat: city.lat,
  lon: city.lon,
  country: city.country,
  inKurdistanRegion: city.inKurdistanRegion,
}));
writeFileSync(
  join(out, "gazetteer-data.ts"),
  header("src/features/geo/gazetteer.ts") +
    "\nexport interface AlertCity {\n" +
    "  id: string;\n" +
    "  names: { en: string; ckb: string; kmr: string; ar: string };\n" +
    "  lat: number;\n" +
    "  lon: number;\n" +
    '  country: "IQ" | "IR" | "TR" | "SY";\n' +
    "  inKurdistanRegion: boolean;\n" +
    "}\n\nexport const CITIES: readonly AlertCity[] = " +
    JSON.stringify(cities, null, 2) +
    ";\n",
);
console.log(`wrote strings.ts (${LOCALES.length} locales) and gazetteer-data.ts (${cities.length} cities)`);
