#!/usr/bin/env node
/**
 * Regenerates `src/features/building/pictograms.generated.ts` from the line
 * pictograms in `assets/artwork/building/*.svg` ("Tag my building"
 * questionnaire: structure types, plan shapes, photo slots).
 *
 * Why a generated TS module: the app has no SVG transformer, so the SVG text
 * is embedded as strings and drawn with react-native-svg's `SvgXml`
 * (`color` drives `currentColor`, so one tint colour themes the drawing).
 *
 * Usage:  node scripts/generate-building-pictograms.mjs
 *         (or: npm run generate:building-pictograms)
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const sourceDir = path.join(root, "assets/artwork/building");
const target = path.join(root, "src/features/building/pictograms.generated.ts");

const files = fs
  .readdirSync(sourceDir)
  .filter((file) => file.endsWith(".svg"))
  .sort();

const entries = files.map((file) => {
  const name = file.replace(/\.svg$/, "");
  const xml = fs
    .readFileSync(path.join(sourceDir, file), "utf8")
    .replace(/<\?xml[^>]*\?>/g, "")
    .replace(/<!--[\s\S]*?-->/g, "")
    .replace(/>\s+</g, "><")
    .trim();
  if (!xml.startsWith("<svg")) {
    throw new Error(`${file}: not an <svg> document`);
  }
  return `  ${JSON.stringify(name)}: ${JSON.stringify(xml)},`;
});

const banner = `// GENERATED by scripts/generate-building-pictograms.mjs from
// assets/artwork/building/*.svg. Do not edit by hand; re-run the script.
`;
fs.writeFileSync(
  target,
  `${banner}\nexport const PICTOGRAM_XML = {\n${entries.join("\n")}\n} as const;\n\nexport type PictogramName = keyof typeof PICTOGRAM_XML;\n`,
);
console.log(`wrote ${path.relative(root, target)} (${files.length} pictograms)`);
